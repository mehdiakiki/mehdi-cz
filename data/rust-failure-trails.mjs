export function getRustFailureTrails(caseId) {
  return rustFailureTrails.filter((trail) => trail.caseIds.includes(caseId));
}

export function getRelatedRustFailureIds(caseId, limit = 3) {
  const related = [];

  for (const trail of getRustFailureTrails(caseId)) {
    const caseIndex = trail.caseIds.indexOf(caseId);
    const nearestCases = trail.caseIds
      .map((relatedCaseId, index) => ({ relatedCaseId, index }))
      .filter(({ relatedCaseId }) => relatedCaseId !== caseId)
      .sort((left, right) => {
        const distance = Math.abs(left.index - caseIndex) - Math.abs(right.index - caseIndex);
        return distance || right.index - left.index;
      });

    for (const { relatedCaseId } of nearestCases) {
      if (related.includes(relatedCaseId)) continue;
      related.push(relatedCaseId);
      if (related.length === limit) return related;
    }
  }

  return related;
}
