use sqlx::PgPool;
use std::path::Path;

// article:start publish
pub async fn publish(pool: &PgPool, id: i64) -> Result<bool, sqlx::Error> {
    let mut tx = pool.begin().await?;
    let key: Option<String> = sqlx::query_scalar(
        "UPDATE uploads SET state = 'ready'
         WHERE id = $1 AND state = 'stored' RETURNING object_key",
    )
    .bind(id)
    .fetch_optional(&mut *tx)
    .await?;
    if let Some(key) = key {
        sqlx::query("INSERT INTO attachments (id, object_key) VALUES ($1, $2)")
            .bind(id)
            .bind(key)
            .execute(&mut *tx)
            .await?;
        tx.commit().await?;
        Ok(true)
    } else {
        tx.rollback().await?;
        Ok(false)
    }
}
// article:end publish

pub async fn cancel(pool: &PgPool, id: i64) -> Result<bool, sqlx::Error> {
    Ok(
        sqlx::query("UPDATE uploads SET state = 'cleanup' WHERE id = $1 AND state = 'stored'")
            .bind(id)
            .execute(pool)
            .await?
            .rows_affected()
            == 1,
    )
}

// article:start cleanup
pub async fn cleanup(
    pool: &PgPool,
    root: &Path,
    id: i64,
) -> Result<bool, Box<dyn std::error::Error>> {
    let key: Option<String> =
        sqlx::query_scalar("SELECT object_key FROM uploads WHERE id = $1 AND state = 'cleanup'")
            .bind(id)
            .fetch_optional(pool)
            .await?;
    let Some(key) = key else {
        return Ok(false);
    };
    // Keys are generated by the service. The lab accepts one simple filename.
    if key.is_empty() || !key.bytes().all(|c| c.is_ascii_alphanumeric() || c == b'-') {
        return Err("invalid generated object key".into());
    }
    match std::fs::remove_file(root.join(key)) {
        Ok(()) => {}
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
        Err(error) => return Err(error.into()),
    }
    sqlx::query("UPDATE uploads SET state = 'cleaned' WHERE id = $1 AND state = 'cleanup'")
        .bind(id)
        .execute(pool)
        .await?;
    Ok(true)
}
// article:end cleanup
